export const MAKES: string[] = [...new Set(VEHICLE_DATA.map((v) => v.make))].sort();

export function getModels(make: string): string[] {
  return [...new Set(
    VEHICLE_DATA.filter((v) => v.make === make).map((v) => v.model)
  )].sort();
}

export function getModelCodes(make: string, model: string): string[] {
  return VEHICLE_DATA
    .filter((v) => v.make === make && v.model === model)
    .map((v) => v.model_code)
    .sort();
}

export function getYears(
  make: string,
  model: string,
  model_code: string,
): { year_from: number; year_to: number | null } | null {
  const entry = VEHICLE_DATA.find(
    (v) => v.make === make && v.model === model && v.model_code === model_code,
  );
  if (!entry) return null;
  return { year_from: entry.year_from, year_to: entry.year_to };
}
