export function getProductBySlug(slug: string): StoreProduct | undefined {
  return CATALOG.find((p) => p.slug === slug);
}

export function getRelatedProducts(slug: string, limit = 4): StoreProduct[] {
  const p = getProductBySlug(slug);
  if (!p) return CATALOG.slice(0, limit);
  return CATALOG.filter((x) => x.slug !== slug && (x.brand === p.brand || x.category === p.category)).slice(0, limit);
}
